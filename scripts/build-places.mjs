// Regenerates dist/places.js from the latest tzdb: zone.tab gives each time zone's reference coordinates, and backward
// maps old names (such as Europe/Kiev or US/Eastern) that some browsers still report. Only Europe, the United States,
// Turkey and the most populous zones elsewhere are listed, to keep the file small; time-of-day.js estimates the rest. Run: node scripts/build-places.mjs
import { writeFileSync } from 'node:fs'

const BASE = 'https://data.iana.org/time-zones/tzdb/'
const get = async file => {
	const response = await fetch(BASE + file)
	if (!response.ok) throw new Error(`${file}: ${response.status}`)
	return response.text()
}
const [version, zoneTab, backward] = await Promise.all(['version', 'zone.tab', 'backward'].map(get))

// zone.tab writes coordinates as ±DDMM[SS]±DDDMM[SS].
const degrees = (text, width) => {
	const sign = text[0] === '-' ? -1 : 1
	const d = +text.slice(1, 1 + width), m = +text.slice(1 + width, 3 + width), s = +(text.slice(3 + width) || 0)
	return Math.round(sign * (d + m / 60 + s / 3600) * 10) / 10
}

// The most populous zones elsewhere, where estimating from the UTC offset alone can be off by an hour or more.
const MAJOR = new Set([
	'Asia/Shanghai', 'Asia/Kolkata', 'Asia/Tokyo', 'Asia/Jakarta', 'Asia/Karachi', 'Asia/Dhaka', 'Asia/Manila', 'Asia/Seoul',
	'Asia/Bangkok', 'Asia/Ho_Chi_Minh', 'Asia/Tehran', 'Asia/Riyadh', 'Asia/Dubai', 'Asia/Singapore', 'Asia/Hong_Kong',
	'Asia/Taipei', 'Asia/Jerusalem', 'Asia/Kuala_Lumpur', 'Asia/Baghdad', 'Asia/Tashkent', 'Asia/Almaty',
	'America/Sao_Paulo', 'America/Mexico_City', 'America/Argentina/Buenos_Aires', 'America/Bogota', 'America/Lima',
	'America/Santiago', 'America/Caracas', 'America/Toronto', 'America/Vancouver',
	'Africa/Lagos', 'Africa/Cairo', 'Africa/Johannesburg', 'Africa/Nairobi', 'Africa/Casablanca', 'Africa/Algiers',
	'Africa/Addis_Ababa', 'Africa/Kinshasa', 'Australia/Sydney', 'Australia/Melbourne', 'Australia/Brisbane', 'Australia/Perth',
	'Pacific/Auckland',
])

const places = {}
for (const line of zoneTab.split('\n')) {
	if (!line || line.startsWith('#')) continue
	const [country, coordinates, zone] = line.split('\t')
	if (!zone.startsWith('Europe/') && country !== 'US' && country !== 'TR' && !MAJOR.has(zone)) continue
	const [, lat, lon] = coordinates.match(/^([+-]\d+)([+-]\d+)$/)
	places[zone] = [degrees(lat, 2), degrees(lon, 3)]
}
for (const line of backward.split('\n')) {
	const link = line.match(/^Link\s+(\S+)\s+(\S+)/)
	if (link && places[link[1]] && !places[link[2]]) places[link[2]] = places[link[1]]
}

const entries = Object.keys(places).sort().map(zone => `'${zone}': [${places[zone].join(', ')}]`)
const rows = []
for (let i = 0; i < entries.length; i += 4) rows.push(`\t${entries.slice(i, i + 4).join(', ')},`)
writeFileSync(new URL('../dist/places.js', import.meta.url), `// Latitude and longitude of each time zone's reference city, in Europe, the United States,
// Turkey and the most populous zones elsewhere, from tzdb ${version.trim()} (zone.tab, plus the old names in backward). Other zones are estimated in time-of-day.js.
// The game reads the player's time zone, never their location, and works out today's sunrise and sunset for this point.
// Generated by scripts/build-places.mjs; regenerate rather than edit.
export const PLACES = {
${rows.join('\n')}
}
`)
console.log(`dist/places.js: ${entries.length} time zones from tzdb ${version.trim()}`)
